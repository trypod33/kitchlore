    // Naive English variants widen the net without a dictionary download.
    private val WORDS: Set<String> = buildSet {
        addAll(BASE_WORDS)
        addAll(COMMON_WORDS)
    }

    private const val MIN_LEN = 4
    private const val MAX_LEN = 15

    /** Corrects single-word OCR garbles inside a line; hyphenated parts are handled piece by piece. */
    private fun applyPhraseFixes(s: String): String =
        PHRASE_FIXES.fold(s) { acc, p -> p.first.replace(acc, p.second) }

    fun fixLine(line: String): String {
        var s = applyPhraseFixes(line)
        s = if (s.contains("0z") || s.contains("0Z"))
            Regex("\\b0[zZ]\\b").replace(s, "oz") else s
        if (s.length < MIN_LEN) return s
        val parts = s.split(" ")
        if (parts.none { needsFix(it) || digitWordFix(it) != null }) return s
        return parts.joinToString(" ") { tok ->
            if (needsFix(tok)) fixWord(tok) else digitWordFix(tok) ?: tok
        }
    }

    // Digits read where letters belong ("teasp0on" for teaspoon): translate
    // the common glyph confusions and accept only an exact lexicon word, so
    // real amounts ("8", "2 1/2") and "0z" are never touched.
    private fun digitWordFix(tok: String): String? {
        val bare = tok.trim('.', ',', '!', '?', ':', ';')
        if (bare.length < MIN_LEN || bare.length > MAX_LEN) return null
        if (!bare.any { it.isDigit() } || !bare.any { it.isLetter() }) return null
        if (bare.contains('-') || bare.contains('/')) return null
        val translated = bare.map { c ->
            when (c) {
                '0' -> 'o'
                '1' -> 'l'
                '5' -> 's'
                '8' -> 'g'
                else -> c
            }
        }.joinToString("")
        val lower = translated.lowercase()
        if (lower !in WORDS) return null
        val punct = tok.substring(bare.length)
        return (if (tok.first().isUpperCase()) lower.replaceFirstChar { it.uppercaseChar() } else lower) + punct
    }

    private fun needsFix(tok: String): Boolean {
        val bare = tok.trim('.', ',', '!', '?', ':', ';')
        if (bare.length < MIN_LEN || bare.length > MAX_LEN) return false
        if (bare.any { it.isDigit() }) return false
        if (bare.contains('/')) return false
        val lower = bare.lowercase()
        if (lower in WORDS) return false
        // hyphenated words are corrected segment by segment
        return true
    }

    /** Returns the corrected token, or the original when there is no unique lexicon match. */
    private fun fixWord(tok: String): String {
        val bare = tok.trim('.', ',', '!', '?', ':', ';')
        val punct = tok.substring(bare.length)
        if (bare.length < MIN_LEN || bare.length > MAX_LEN || bare.any { it.isDigit() }) return tok
        if (bare.contains('-')) {
            val fixed = bare.split("-").joinToString("-") { seg -> fixSegment(seg, tok) ?: seg }
            if (fixed != bare) return fixed + punct
            return tok
        }
        val fixed = fixSegment(bare, tok) ?: return tok
        return fixed + punct
    }

    private fun fixSegment(seg: String, original: String): String? {
        if (seg.length < MIN_LEN || seg.length > MAX_LEN) return null
        val lower = seg.lowercase()
        if (lower in WORDS) return null
        // A trailing-s swap is plural confusion, not an OCR garble: never
        // "correct" breast->breasts or inches->pinches on that shape.
        val matches = candidates(lower)
            .filter { it in WORDS && it != lower.dropLast(1) && it != lower + "s" }
            .distinct()
        if (matches.size != 1) return null
        val fixed = matches.single()
        // restore the original casing shape
        return when {
            original.take(seg.length) == original.take(seg.length).uppercase() && original != original.lowercase() && original.take(seg.length).uppercase() == original.take(seg.length) -> fixed.uppercase()
            original.first().isUpperCase() -> fixed.replaceFirstChar { it.uppercaseChar() }
            else -> fixed
        }
    }

    // One-edit candidates: substitutions, insertions, deletions, transpositions,
    // plus the run-together pairs the recognizer loves (rn/m, nn/m, vv/w).
    private fun candidates(w: String): List<String> {
        val out = mutableListOf<String>()
        val letters = ('a'..'z')
        for (i in w.indices) {
            for (c in letters) if (c != w[i]) out.add(w.replaceRange(i, i + 1, c.toString()))
            out.add(w.removeRange(i, i + 1))
        }
        for (i in 0..w.length) {
            for (c in letters) out.add(w.substring(0, i) + c + w.substring(i))
        }
        for (i in 0 until w.length - 1) {
            if (w[i] != w[i + 1]) out.add(w.substring(0, i) + w[i + 1] + w[i] + w.substring(i + 2))
        }
        for (pair in listOf("rn" to "m", "nn" to "m", "vv" to "w", "m" to "rn", "m" to "nn", "w" to "vv")) {
            var idx = w.indexOf(pair.first)
            while (idx >= 0) {
                out.add(w.substring(0, idx) + pair.second + w.substring(idx + pair.first.length))
                idx = w.indexOf(pair.first, idx + 1)
            }
        }
        return out
    }

    // Is this a word the lexicon knows? Used to tell real one-word
    // ingredient tails ("broth") from torn page-margin fragments ("vder,").
    fun isKnownWord(token: String): Boolean {
        val w = token.trim(',', '.', ';', ':', '!', '?', '(', ')').lowercase()
        if (w.length < 2) return false
        return w in WORDS
    }
