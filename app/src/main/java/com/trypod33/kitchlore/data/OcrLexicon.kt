    private val PHRASE_FIXES = listOf(
        Regex("(?i)\\bto bowling\\b") to "to boiling",
        Regex("(?i)\\borange edges\\b") to "orange wedges",
        Regex("(?i)\\bstudied\\b") to "studded",
