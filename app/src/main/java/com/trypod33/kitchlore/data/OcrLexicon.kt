/**
 * A small offline lexicon of recipe words, used to repair character-level OCR
 * garbles before parsing. The recognizer drops real misreads on recipe cards
 * ("SMOCTHIE" for SMOOTHIE, "buttor" for button), and a word is only ever
 * rewritten when the garble sits one edit away from exactly one word in this
 * list, so unknown ingredient names pass through untouched and ambiguous
 * matches are left alone for the reviewer.
